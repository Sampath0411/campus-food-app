type Key = keyof typeof dict.en;

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: Key) => string;
};

const I18nCtx = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem("bb:lang") as Lang | null;
    return saved && ["en", "hi", "te", "ta"].includes(saved) ? saved : "en";
  });

  useEffect(() => {
    localStorage.setItem("bb:lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (k: Key) => (dict[lang] as any)[k] ?? dict.en[k] ?? k;

  return (
    <I18nCtx.Provider value={{ lang, setLang: setLangState, t }}>
      {children}
    </I18nCtx.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
